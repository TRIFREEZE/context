"""Offline admin CLI for the Context licensing backend (no network exposure).

Run from the backend folder:

    python -m app.admin init-keys                 create the signing key (once) and print the public key
    python -m app.admin public-key                print the public key again
    python -m app.admin create [--max-devices 2] [--expires-days N] [--note TEXT]
    python -m app.admin list
    python -m app.admin activations [KEY]
    python -m app.admin revoke KEY
    python -m app.admin restore KEY
    python -m app.admin reset KEY                 deactivate every device on a license
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from . import licenses
from .config import BACKEND_DIR, load_settings
from .crypto import generate_private_key, load_private_key, public_key_b64
from .db import connect

PLUGIN_KEY_FILE = BACKEND_DIR.parent / "licensing" / "license_public_key.txt"


def write_plugin_public_key(pub: str, path: Path | None = None) -> None:
    path = path or PLUGIN_KEY_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "# Ed25519 PUBLIC key used by the plugin to verify license tokens.\n"
        "# Safe to commit. Generated by: python -m app.admin init-keys\n"
        f"{pub}\n", encoding="ascii")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m app.admin", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    k = sub.add_parser("init-keys", help="create the Ed25519 signing key")
    k.add_argument("--force", action="store_true", help="replace an existing key (all issued tokens become invalid)")
    k.add_argument("--no-plugin-file", action="store_true", help="do not write licensing/license_public_key.txt")
    sub.add_parser("public-key", help="print the public key")

    c = sub.add_parser("create", help="create a license")
    c.add_argument("--max-devices", type=int, default=None)
    c.add_argument("--expires-days", type=int, default=None)
    c.add_argument("--note", default="")

    sub.add_parser("list", help="list licenses")
    a = sub.add_parser("activations", help="list activations")
    a.add_argument("key", nargs="?")
    for name in ("revoke", "restore", "reset"):
        p = sub.add_parser(name)
        p.add_argument("key")

    args = ap.parse_args(argv)
    settings = load_settings()

    if args.cmd == "init-keys":
        try:
            key = generate_private_key(settings.signing_key_path, overwrite=args.force)
        except FileExistsError as e:
            print(f"error: {e}", file=sys.stderr)
            return 1
        pub = public_key_b64(key)
        print(f"Private signing key written to: {settings.signing_key_path}")
        print("KEEP IT SECRET. Never commit it, never put it in GitHub, never ship it in the plugin.")
        print(f"\nPublic key (goes into the plugin): {pub}")
        if not args.no_plugin_file:
            write_plugin_public_key(pub)
            print(f"Also written to {PLUGIN_KEY_FILE} - commit that file and rebuild the plugin.")
        return 0

    if args.cmd == "public-key":
        print(public_key_b64(load_private_key(settings.signing_key_path)))
        return 0

    conn = connect(settings.db_path)
    try:
        if args.cmd == "create":
            max_devices = args.max_devices or settings.default_max_devices
            key = licenses.create_license(conn, max_devices, args.expires_days, args.note)
            print(key)
            print(f"(max devices: {max_devices}" + (f", expires in {args.expires_days} days" if args.expires_days else ", no expiry")
                  + ") - the full key is shown only once; the database stores only its hash.", file=sys.stderr)
        elif args.cmd == "list":
            rows = licenses.list_licenses(conn)
            if not rows:
                print("No licenses yet. Create one with: python -m app.admin create")
            for r in rows:
                print(f"#{r['id']:<4} CTX-****-****-****-{r['key_hint']}  {r['status']:<8} devices {r['active_devices']}/{r['max_devices']}  "
                      f"created {r['created_at']}  expires {r['expires_at'] or 'never'}  {r['note']}")
        elif args.cmd == "activations":
            for r in licenses.list_activations(conn, args.key):
                state = "deactivated " + r["deactivated_at"] if r["deactivated_at"] else "active"
                print(f"license ...{r['key_hint']}  device {r['device_id']}  v{r['plugin_version']}  "
                      f"activated {r['activated_at']}  last seen {r['last_seen_at']}  {state}")
        elif args.cmd == "revoke":
            licenses.set_status(conn, args.key, "revoked")
            print("revoked")
        elif args.cmd == "restore":
            licenses.set_status(conn, args.key, "active")
            print("restored")
        elif args.cmd == "reset":
            print(f"deactivated {licenses.reset_activations(conn, args.key)} device(s)")
    except licenses.LicenseError as e:
        print(f"error: {e.message}", file=sys.stderr)
        return 1
    finally:
        conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
